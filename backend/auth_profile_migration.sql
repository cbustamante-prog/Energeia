-- PostgreSQL/Supabase only. Apply once to an existing Energeia database.
-- This migration preserves existing accounts and household data. Existing users
-- will be asked to complete the new profile fields when they next sign in.

ALTER TABLE "Users"
    ALTER COLUMN full_name DROP NOT NULL,
    ALTER COLUMN password_hash DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS first_name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS middle_name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS last_name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS country VARCHAR(100),
    ADD COLUMN IF NOT EXISTS region VARCHAR(100),
    ADD COLUMN IF NOT EXISTS city VARCHAR(100),
    ADD COLUMN IF NOT EXISTS barangay VARCHAR(100),
    ADD COLUMN IF NOT EXISTS street_address VARCHAR(255),
    ADD COLUMN IF NOT EXISTS unit_number VARCHAR(100),
    ADD COLUMN IF NOT EXISTS postal_code VARCHAR(32),
    ADD COLUMN IF NOT EXISTS phone_number VARCHAR(32),
    ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS "OAuthIdentities" (
    identity_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES "Users"(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    provider VARCHAR(20) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    provider_email VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_oauth_provider_subject UNIQUE (provider, subject)
);
CREATE INDEX IF NOT EXISTS idx_oauth_identity_user ON "OAuthIdentities"(user_id);

CREATE TABLE IF NOT EXISTS "OAuthStates" (
    state_id VARCHAR(64) PRIMARY KEY,
    provider VARCHAR(20) NOT NULL,
    user_id INTEGER REFERENCES "Users"(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    expires_at TIMESTAMP NOT NULL,
    consumed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "PasswordResetTokens" (
    token_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES "Users"(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_password_reset_user ON "PasswordResetTokens"(user_id);

ALTER TABLE "OAuthIdentities" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "OAuthStates" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "PasswordResetTokens" ENABLE ROW LEVEL SECURITY;
